/**
 * Helper to match exact Hebrew words with common prefixes (ב, ל, מ, כ, ה, ו, כש, ש).
 * Prevents substring false-positives like 'שבת' inside 'מחושבת' or 'השבתה'!
 */
function hasHebrewWord(text: string, words: string[]): boolean {
  const pattern = new RegExp(`(^|[\\s,?.!;:"'()\\[\\]])(ו|ב|ל|מ|כ|ה|כש|ש)?(${words.join('|')})($|[\\s,?.!;:"'()\\[\\]])`, 'i');
  return pattern.test(text);
}

