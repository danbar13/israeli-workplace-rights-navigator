function hasHebrewWord(text: string, words: string[]): boolean {
  const pattern = new RegExp(`(^|[\\s,?.!;:"'()\\[\\]])(ו|ב|ל|מ|כ|ה|כש|ש)?(${words.join('|')})($|[\\s,?.!;:"'()\\[\\]])`, 'i');
  return pattern.test(text);
}

